/** 从中文串里抽关键词：优先命中情绪词典的词，否则取较长的 2–4 字词组 */
function extractKeyword(text) {
  for (const emo of EMOTIONS) {
    for (const w of emo.words) {
      if (text.includes(w)) return { kw: w, emotion: emo.key };
    }
  }
  const cjk = text.replace(/[^一-龥]/g, '');
  let best = '';
  for (let n = 4; n >= 2; n--) {
    for (let i = 0; i + n <= cjk.length; i++) {
      const g = cjk.slice(i, i + n);
      if (STOPWORDS.has(g)) continue;
      if (g.length > best.length) best = g;
    }
    if (best) break;
  }
  return { kw: best || '此刻', emotion: 'default' };
}

// 极短中段：当中段过长、导致整句超过 50 字上限时启用
const SHORT_MIDDLES = {
  焦虑: '这不必现在就有解法。',
  迷茫: '也许不必现在选定。',
  疲惫: '这更像需要休息。',
  难过: '这似乎值得停一会儿。',
  愤怒: '这情绪大概有来处。',
  期待: '这大概不必安排太细。',
  平静: '这或许只是稳住了。',
  default: '这似乎不用急着下结论。'
};

/**
 * 生成一句占卜师回复。
 * @param {string} text 用户输入
 * @param {number} turn 已进行轮次（从 1 开始）
 * @returns {string}
 */
export function offlineDiviner(text, turn = 1) {
  const { kw, emotion } = extractKeyword(String(text || ''));
  const pool = OPENERS[emotion] || OPENERS.default;
  const mids = MIDDLES[emotion] || MIDDLES.default;
  const opener = (pool[(turn - 1) % pool.length]).replace('{kw}', kw);
  const middle = mids[(turn - 1) % mids.length];
  const exit = EXITS[(turn - 1) % EXITS.length];

  let out = `${opener}\n\n${middle}\n\n${exit}`;
  // 系统提示词约束：每次回复不超过 50 字
  if (out.length > 50) {
    out = `${opener}\n\n${SHORT_MIDDLES[emotion] || SHORT_MIDDLES.default}\n\n${exit}`;
  }
  return out;
}

/** 无关键词、输入为空时的通用回复 */
export function offlineIdle() {
  return '我在这里。\n\n你不必急着把话说完整。\n\n你想接着说，还是先看一张牌？';
}
